
<?php 

ini_set('display_errors', '0');
error_reporting(E_ALL);

header('Content-Type: application/json; charset=utf-8');
header('Cache-Control: no-store, private');
header('X-Content-Type-Options: nosniff');

function courseApiResponse(int $httpCode, array $data): never
{
    http_response_code($httpCode);

    echo json_encode(
        $data,
        JSON_INVALID_UTF8_SUBSTITUTE | JSON_UNESCAPED_UNICODE
    );

    exit;
}

function courseApiDeleteUploadedFile(?string $path): void
{
    if ($path !== null && is_file($path) && !is_link($path)) {
        unlink($path);
    }
}

function courseApiValidThumbnailPath(?string $path): ?string
{
    if ($path === null || $path === '') {
        return null;
    }

    $prefix = 'uploads/thumbnails/';

    if (!str_starts_with($path, $prefix)) {
        return null;
    }

    $filename = substr($path, strlen($prefix));

    // Only accept the filenames generated by this API.
    if (
        preg_match('/\A[a-f0-9]{32}\.(?:jpg|png|webp)\z/', $filename) !== 1
    ) {
        return null;
    }

    return $path;
}

try {
    require_once __DIR__ . '/../includes/config.php';
} catch (Throwable $error) {
    error_log('Course API startup failed: ' . $error->getMessage());

    courseApiResponse(500, [
        'status' => 'error',
        'message' => 'Something went wrong on our side. Please try again.'
    ]);
}

// This API accepts POST requests only.
if (($_SERVER['REQUEST_METHOD'] ?? '') !== 'POST') {
    header('Allow: POST');

    courseApiResponse(405, [
        'status' => 'error',
        'message' => 'This endpoint only accepts course creation and update requests.'
    ]);
}

// Existing forms without an action continue to create courses.
$action = is_string($_POST['action'] ?? null)
    ? trim($_POST['action'])
    : 'create';

if (!in_array($action, ['create', 'update'], true)) {
    courseApiResponse(400, [
        'status' => 'error',
        'message' => 'Invalid course action.'
    ]);
}

// Authenticate the user.
$user = currentUser();

if ($user === null) {
    courseApiResponse(401, [
        'status' => 'error',
        'message' => 'Please sign in to manage courses.'
    ]);
}

if (($user['role'] ?? '') !== 'instructor') {
    courseApiResponse(403, [
        'status' => 'error',
        'message' => 'Only instructors can manage courses.'
    ]);
}

// Verify the CSRF token.
if (session_status() !== PHP_SESSION_ACTIVE) {
    session_start();
}

$sessionToken = $_SESSION['instructor_course_form_csrf'] ?? '';
$submittedToken = $_POST['csrf_token'] ?? '';

if (
    !is_string($sessionToken) ||
    $sessionToken === '' ||
    !is_string($submittedToken) ||
    !hash_equals($sessionToken, $submittedToken)
) {
    courseApiResponse(403, [
        'status' => 'error',
        'message' => 'Your session could not be verified. Reload the page and try again.'
    ]);
}

/*
|--------------------------------------------------------------------------
| Validate the submitted fields
|--------------------------------------------------------------------------
*/

$title = is_string($_POST['title'] ?? null)
    ? trim($_POST['title'])
    : '';

$description = is_string($_POST['description'] ?? null)
    ? trim($_POST['description'])
    : '';

$categoryInput = is_string($_POST['category_id'] ?? null)
    ? trim($_POST['category_id'])
    : '';

$status = is_string($_POST['status'] ?? null)
    ? $_POST['status']
    : '';

if (!mb_check_encoding($title, 'UTF-8')) {
    courseApiResponse(422, [
        'status' => 'error',
        'message' => 'The course title must contain valid UTF-8 text.'
    ]);
}

if ($title === '' || mb_strlen($title, 'UTF-8') > 190) {
    courseApiResponse(422, [
        'status' => 'error',
        'message' => 'Enter a course title between 1 and 190 characters.'
    ]);
}

if (!mb_check_encoding($description, 'UTF-8')) {
    courseApiResponse(422, [
        'status' => 'error',
        'message' => 'The course description must contain valid UTF-8 text.'
    ]);
}

if (strlen($description) > 65535) {
    courseApiResponse(422, [
        'status' => 'error',
        'message' => 'The course description is too long.'
    ]);
}

if (!in_array($status, ['draft', 'published'], true)) {
    courseApiResponse(422, [
        'status' => 'error',
        'message' => 'Choose draft or published as the course status.'
    ]);
}

$categoryId = null;

if ($categoryInput !== '') {
    $validatedCategory = filter_var(
        $categoryInput,
        FILTER_VALIDATE_INT,
        ['options' => ['min_range' => 1]]
    );

    if ($validatedCategory === false) {
        courseApiResponse(422, [
            'status' => 'error',
            'message' => 'Choose a valid course category.'
        ]);
    }

    $categoryId = (int) $validatedCategory;
}

/*
|--------------------------------------------------------------------------
| Validate the course ID and ownership for updates
|--------------------------------------------------------------------------
*/

$courseId = null;
$existingCourse = null;

try {
    $pdo = db();

    if ($action === 'update') {
        $validatedCourseId = filter_var(
            $_POST['course_id'] ?? null,
            FILTER_VALIDATE_INT,
            ['options' => ['min_range' => 1]]
        );

        if ($validatedCourseId === false) {
            courseApiResponse(422, [
                'status' => 'error',
                'message' => 'A valid course ID is required.'
            ]);
        }

        $courseId = (int) $validatedCourseId;

        $findCourse = $pdo->prepare(
            'SELECT id, thumbnail
             FROM courses
             WHERE id = :course_id
               AND instructor_id = :instructor_id
             LIMIT 1'
        );

        $findCourse->execute([
            'course_id' => $courseId,
            'instructor_id' => (int) $user['id'],
        ]);

        $existingCourse = $findCourse->fetch(PDO::FETCH_ASSOC);

        if (!$existingCourse) {
            courseApiResponse(404, [
                'status' => 'error',
                'message' => 'Course not found or you do not have permission to edit it.'
            ]);
        }
    }

    // Validate that the selected category exists.
    if ($categoryId !== null) {
        $categoryCheck = $pdo->prepare(
            'SELECT id FROM categories WHERE id = :id LIMIT 1'
        );

        $categoryCheck->execute(['id' => $categoryId]);

        if ($categoryCheck->fetchColumn() === false) {
            courseApiResponse(422, [
                'status' => 'error',
                'message' => 'The selected category is unavailable.'
            ]);
        }
    }
} catch (Throwable $error) {
    error_log('Course API validation failed: ' . $error->getMessage());

    courseApiResponse(500, [
        'status' => 'error',
        'message' => 'Unable to validate the course. Please try again.'
    ]);
}

/*
|--------------------------------------------------------------------------
| Validate and save the optional thumbnail
|--------------------------------------------------------------------------
*/

$thumbnailPath = null;
$thumbnailDestination = null;

$upload = $_FILES['thumbnail'] ?? null;

if (is_array($upload)) {
    $uploadError = (int) ($upload['error'] ?? UPLOAD_ERR_NO_FILE);

    if ($uploadError !== UPLOAD_ERR_NO_FILE) {
        if ($uploadError !== UPLOAD_ERR_OK) {
            $message = in_array(
                $uploadError,
                [UPLOAD_ERR_INI_SIZE, UPLOAD_ERR_FORM_SIZE],
                true
            )
                ? 'The course image must be no larger than 5 MB.'
                : 'The course image could not be uploaded.';

            courseApiResponse(422, [
                'status' => 'error',
                'message' => $message
            ]);
        }

        if ((int) ($upload['size'] ?? 0) > 5 * 1024 * 1024) {
            courseApiResponse(422, [
                'status' => 'error',
                'message' => 'The course image must be no larger than 5 MB.'
            ]);
        }

        $temporaryPath = (string) ($upload['tmp_name'] ?? '');

        if (
            $temporaryPath === '' ||
            !is_uploaded_file($temporaryPath)
        ) {
            courseApiResponse(422, [
                'status' => 'error',
                'message' => 'The uploaded course image is invalid.'
            ]);
        }

        $imageInfo = @getimagesize($temporaryPath);

        $mimeType = (new finfo(FILEINFO_MIME_TYPE))
            ->file($temporaryPath);

        $allowedImages = [
            'image/jpeg' => 'jpg',
            'image/png' => 'png',
            'image/webp' => 'webp',
        ];

        if (
            !is_array($imageInfo) ||
            !is_string($mimeType) ||
            !isset($allowedImages[$mimeType])
        ) {
            courseApiResponse(422, [
                'status' => 'error',
                'message' => 'Upload a valid JPEG, PNG, or WebP image.'
            ]);
        }

        if ($imageInfo[0] > 6000 || $imageInfo[1] > 6000) {
            courseApiResponse(422, [
                'status' => 'error',
                'message' => 'Image dimensions cannot exceed 6000 by 6000 pixels.'
            ]);
        }

        $thumbnailDirectory = dirname(__DIR__)
            . DIRECTORY_SEPARATOR
            . 'uploads'
            . DIRECTORY_SEPARATOR
            . 'thumbnails';

        if (
            !is_dir($thumbnailDirectory) &&
            !mkdir($thumbnailDirectory, 0755, true) &&
            !is_dir($thumbnailDirectory)
        ) {
            error_log('Course API could not create the thumbnail directory.');

            courseApiResponse(500, [
                'status' => 'error',
                'message' => 'Unable to prepare the course image folder.'
            ]);
        }

        $filename = bin2hex(random_bytes(16))
            . '.'
            . $allowedImages[$mimeType];

        $thumbnailDestination = $thumbnailDirectory
            . DIRECTORY_SEPARATOR
            . $filename;

        $thumbnailPath = 'uploads/thumbnails/' . $filename;

        if (!move_uploaded_file($temporaryPath, $thumbnailDestination)) {
            error_log('Course API could not save the uploaded thumbnail.');

            courseApiResponse(500, [
                'status' => 'error',
                'message' => 'Unable to save the course image.'
            ]);
        }
    }
}

/*
|--------------------------------------------------------------------------
| Create or update the course
|--------------------------------------------------------------------------
*/

try {
    if ($action === 'create') {
        $createCourse = $pdo->prepare(
            'INSERT INTO courses
                (instructor_id, category_id, title, description, thumbnail, status)
             VALUES
                (:instructor_id, :category_id, :title, :description, :thumbnail, :status)'
        );

        $createCourse->execute([
            'instructor_id' => (int) $user['id'],
            'category_id' => $categoryId,
            'title' => $title,
            'description' => $description === '' ? null : $description,
            'thumbnail' => $thumbnailPath,
            'status' => $status,
        ]);

        $courseId = (int) $pdo->lastInsertId();

        courseApiResponse(201, [
            'status' => 'success',
            'message' => 'Your course was created successfully.',
            'course_id' => $courseId,
            'redirect' => url('instructor/courses/coureses_add_form.php?created=1')
        ]);
    }

    // Update: keep the current thumbnail unless a new one was uploaded.
    $finalThumbnail = $thumbnailPath !== null
        ? $thumbnailPath
        : ($existingCourse['thumbnail'] ?? null);

    $updateCourse = $pdo->prepare(
        'UPDATE courses
         SET category_id = :category_id,
             title = :title,
             description = :description,
             thumbnail = :thumbnail,
             status = :status
         WHERE id = :course_id
           AND instructor_id = :instructor_id'
    );

    $updateCourse->execute([
        'category_id' => $categoryId,
        'title' => $title,
        'description' => $description === '' ? null : $description,
        'thumbnail' => $finalThumbnail,
        'status' => $status,
        'course_id' => $courseId,
        'instructor_id' => (int) $user['id'],
    ]);

    // Delete the old thumbnail only after the database update succeeds.
    if ($thumbnailPath !== null) {
        $oldThumbnail = courseApiValidThumbnailPath(
            is_string($existingCourse['thumbnail'] ?? null)
                ? $existingCourse['thumbnail']
                : null
        );

        if ($oldThumbnail !== null) {
            $oldThumbnailPath = dirname(__DIR__)
                . DIRECTORY_SEPARATOR
                . str_replace(
                    '/',
                    DIRECTORY_SEPARATOR,
                    $oldThumbnail
                );

            courseApiDeleteUploadedFile($oldThumbnailPath);
        }
    }

    courseApiResponse(200, [
        'status' => 'success',
        'message' => 'Your course was updated successfully.',
        'course_id' => $courseId,
        'redirect' => url(
            'instructor/courses/courses_edit_form.php?id='
            . $courseId
            . '&updated=1'
        )
    ]);

} catch (Throwable $error) {
    // Avoid leaving a newly uploaded image behind if saving fails.
    courseApiDeleteUploadedFile($thumbnailDestination);

    error_log('Instructor course save failed: ' . $error->getMessage());

    courseApiResponse(500, [
        'status' => 'error',
        'message' => 'The course could not be saved. Please try again.'
    ]);
}
